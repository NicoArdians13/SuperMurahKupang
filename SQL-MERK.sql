-- Jalankan di proyek Supabase yang sama dengan website.
-- Hanya menambah master merk dan kolom relasi opsional pada produk.
BEGIN;
CREATE TABLE IF NOT EXISTS public.brands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
  image TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS brands_name_normalized_unique
  ON public.brands (lower(trim(name)));
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS brand_id BIGINT;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.products'::regclass
      AND conname = 'products_brand_id_fkey'
  ) THEN
    ALTER TABLE public.products
      ADD CONSTRAINT products_brand_id_fkey
      FOREIGN KEY (brand_id) REFERENCES public.brands(id) ON DELETE RESTRICT;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS products_brand_id_idx ON public.products (brand_id);
ALTER TABLE public.brands ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.brands TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.brands TO authenticated;
DO $$ DECLARE brand_sequence TEXT; BEGIN
  brand_sequence := pg_get_serial_sequence('public.brands', 'id');
  IF brand_sequence IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', brand_sequence);
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='brands' AND policyname='brands_public_read') THEN
    CREATE POLICY brands_public_read ON public.brands
      FOR SELECT TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='brands' AND policyname='brands_admin_manage') THEN
    CREATE POLICY brands_admin_manage ON public.brands
      FOR ALL TO authenticated
      USING (EXISTS (SELECT 1 FROM public.admin_users WHERE id=(SELECT auth.uid()) AND role='admin'))
      WITH CHECK (EXISTS (SELECT 1 FROM public.admin_users WHERE id=(SELECT auth.uid()) AND role='admin'));
  END IF;
END $$;
COMMIT;
